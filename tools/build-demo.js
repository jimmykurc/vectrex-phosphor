#!/usr/bin/env node
/**
 * Builds the built-in demo ROM:
 *   1. generates demo/tables.inc (sine and perspective tables)
 *   2. assembles demo/demo.asm with tools/asm6809.js
 *   3. writes src/demo/demo-rom.js (an 8 KB image for the $E000 ROM slot)
 *
 * Usage: node tools/build-demo.js [--check]
 *   --check  only verify that the committed files are up to date
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { assemble } from './asm6809.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const demoDir = join(root, 'demo');

export function generateTables() {
  const rows = (values) => {
    const out = [];
    for (let i = 0; i < values.length; i += 16) out.push(`           FCB ${values.slice(i, i + 16).join(',')}`);
    return out.join('\n');
  };
  const sin = Array.from({ length: 256 }, (_, i) => Math.round(Math.sin((i / 256) * 2 * Math.PI) * 127));
  // Perspective factor (x/256) indexed by z + 128: nearer points (z > 0) are larger.
  const persp = Array.from({ length: 256 }, (_, i) => Math.min(255, Math.round((205 * 400) / (400 - (i - 128)))));
  return [
    '; Generated by tools/build-demo.js - do not edit',
    'sintab:',
    rows(sin),
    'persp:',
    rows(persp),
    '',
  ].join('\n');
}

export function buildDemo() {
  const tables = generateTables();
  const source = readFileSync(join(demoDir, 'demo.asm'), 'utf8');
  const result = assemble(source, {
    fileName: 'demo.asm',
    include: (name) => (name === 'tables.inc' ? tables : readFileSync(join(demoDir, name), 'utf8')),
  });
  const rom = result.extract(0xe000, 0x10000, 0xff);
  const b64 = Buffer.from(rom).toString('base64');
  const lines = b64.match(/.{1,96}/g).map((l) => `  '${l}'`).join(',\n');
  const module = `// Generated by tools/build-demo.js from demo/demo.asm - do not edit.
// Original program, MIT licensed. Loaded into the $E000 system ROM slot.
const b64 = [
${lines},
].join('');

export const DEMO_ROM = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
`;
  return { tables, rom, module, symbols: result.symbols };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { tables, module, rom, symbols } = buildDemo();
  const tablesPath = join(demoDir, 'tables.inc');
  const modPath = join(root, 'src', 'demo', 'demo-rom.js');
  if (process.argv.includes('--check')) {
    const ok = readFileSync(tablesPath, 'utf8') === tables && readFileSync(modPath, 'utf8') === module;
    console.log(ok ? 'demo ROM is up to date' : 'demo ROM is stale: run node tools/build-demo.js');
    process.exit(ok ? 0 : 1);
  }
  writeFileSync(tablesPath, tables);
  writeFileSync(modPath, module);
  let used = 0;
  for (const b of rom) if (b !== 0xff) used++;
  const end = Object.entries(symbols).find(([k]) => k === 'G_SP');
  console.log(`demo ROM written: ${rom.length} bytes slot, code+data ends near $${end ? end[1].toString(16) : '?'}, ${used} non-$FF bytes`);
}
